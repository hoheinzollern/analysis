Section dprod_measure_probability.
Context {R : realType} n (d : 'I_n -> measure_display)
  (T : forall i, measurableType (d i)) (P : forall i, probability (T i) R).
Local Open Scope ereal_scope.

Let dprod_setT : (\X_(i < n) P i) setT = 1.
Proof. by rewrite dprod_measureT; apply: big1 => i _; exact: probability_setT. Qed.

HB.instance Definition _ :=
  Measure_isProbability.Build _ _ _ (\X_(i < n) P i) dprod_setT.

Lemma dprod_probability_dcoor i (A : set (T i)) : measurable A ->
  (\X_(j < n) P j) ((fun x => x i) @^-1` A) = P i A.
Proof.
move=> mA.
have -> : (fun x : forall j, T j => x i) @^-1` A =
    dprod_set (dfwith (fun j => [set: T j]) A).
  apply/seteqP; split => [x Ax j|x Ax]; last by have := Ax i; rewrite dfwith_in.
  by have [<-|ij] := eqVneq i j; [rewrite dfwith_in|rewrite dfwith_out].
have mA' : forall j, measurable (dfwith (fun j => [set: T j]) A j).
  by move=> j; have [<-|ij] := eqVneq i j; [rewrite dfwith_in|rewrite dfwith_out].
rewrite (dprod_measureX _ mA') (bigD1 i)//= dfwith_in.
have -> : \prod_(j < n | j != i) P j (dfwith (fun j => [set: T j]) A j) = 1.
  by apply: big1 => j ji; rewrite dfwith_out ?probability_setT// eq_sym.
by rewrite mule1.
Qed.

End dprod_measure_probability.

(* ## Integration with respect to the product measure *)

Section integral_dprod_measure.
Context {R : realType}.
Local Open Scope ereal_scope.

Lemma dprod_measure_pushforward n (d : 'I_n.+1 -> measure_display)
    (T : forall i, measurableType (d i))
    (P : forall i, {sigma_finite_measure set (T i) -> \bar R}) :
  dprod_measure P = pushforward (P ord0 \x^ \X_(j < n) P (lift ord0 j))
    (fun p => dcons p.1 p.2).
Proof. by apply/funext => A; rewrite /= image_dsplit. Qed.

Lemma ge0_integral_dcons n (d : 'I_n.+1 -> measure_display)
    (T : forall i, measurableType (d i))
    (P : forall i, {sigma_finite_measure set (T i) -> \bar R})
    (f : (forall i, T i) -> \bar R) :
    measurable_fun [set: forall i, T i] f -> (forall x, 0 <= f x) ->
  \int[dprod_measure P]_x f x =
  \int[P ord0 \x^ \X_(j < n) P (lift ord0 j)]_p f (dcons p.1 p.2).
Proof.
move=> mf f0; rewrite dprod_measure_pushforward.
by rewrite (@ge0_integral_pushforward _ _ _ _ R _ (@measurable_dcons n d T) _ setT
  f measurableT mf (fun x _ => f0 x)) preimage_setT.
Qed.

Lemma integrable_dcons n (d : 'I_n.+1 -> measure_display)
    (T : forall i, measurableType (d i))
    (P : forall i, {sigma_finite_measure set (T i) -> \bar R})
    (f : (forall i, T i) -> \bar R) :
  (dprod_measure P).-integrable setT f <->
  (P ord0 \x^ \X_(j < n) P (lift ord0 j)).-integrable setT
    (fun p => f (dcons p.1 p.2)).
Proof.
have habs (g : (forall i, T i) -> \bar R) : measurable_fun setT g ->
    \int[dprod_measure P]_x `|g x| =
    \int[P ord0 \x^ \X_(j < n) P (lift ord0 j)]_p `|g (dcons p.1 p.2)|.
  move=> mg; apply: (@ge0_integral_dcons _ _ _ P (abse \o g)).
    exact: measurableT_comp.
  by move=> x; exact: abse_ge0.
split=> /integrableP[mf foo]; apply/integrableP; split.
- exact: (measurableT_comp mf (@measurable_dcons n d T)).
- by rewrite -habs.
- have -> : f = (fun p => f (dcons p.1 p.2)) \o dsplit.
    by apply/funext => x /=; rewrite dsplitK.
  exact: (measurableT_comp mf (@measurable_dsplit n d T)).
- rewrite habs//.
  have -> : f = (fun p => f (dcons p.1 p.2)) \o dsplit.
    by apply/funext => x /=; rewrite dsplitK.
  exact: (measurableT_comp mf (@measurable_dsplit n d T)).
Qed.

Lemma integral_dcons n (d : 'I_n.+1 -> measure_display)
    (T : forall i, measurableType (d i))
    (P : forall i, {sigma_finite_measure set (T i) -> \bar R})
    (f : (forall i, T i) -> \bar R) :
    (dprod_measure P).-integrable setT f ->
  \int[dprod_measure P]_x f x =
  \int[P ord0 \x^ \X_(j < n) P (lift ord0 j)]_p f (dcons p.1 p.2).
Proof.
move=> intf; have mf := measurable_int _ intf.
rewrite dprod_measure_pushforward.
rewrite (@integral_pushforward _ _ _ _ R _ (@measurable_dcons n d T) _ setT f mf)
  ?preimage_setT//.
exact/integrable_dcons.
Qed.

Lemma ge0_integral_dcoor n (d : 'I_n -> measure_display)
    (T : forall i, measurableType (d i)) (P : forall i, probability (T i) R)
    i (f : T i -> \bar R) :
    measurable_fun [set: T i] f -> (forall y, 0 <= f y) ->
  \int[\X_(j < n) P j]_x f (x i) = \int[P i]_y f y.
Proof.
move=> mf f0.
transitivity (\int[pushforward (\X_(j < n) P j) (fun x : forall j, T j => x i)]_y
    f y); last first.
  apply: eq_measure_integral => [|mphi A mA _].
    exact: (@measurable_dcoor n d T i).
  exact: dprod_probability_dcoor.
by rewrite (@ge0_integral_pushforward _ _ _ _ R _ (@measurable_dcoor n d T i)
  (\X_(j < n) P j) setT f measurableT mf (fun y _ => f0 y)) preimage_setT.
Qed.

Lemma integrable_dcoor n (d : 'I_n -> measure_display)
    (T : forall i, measurableType (d i)) (P : forall i, probability (T i) R)
    i (f : T i -> \bar R) : measurable_fun [set: T i] f ->
  (\X_(j < n) P j).-integrable setT (fun x => f (x i)) <->
  (P i).-integrable setT f.
Proof.
move=> mf.
have h : \int[\X_(j < n) P j]_x `|f (x i)| = \int[P i]_y `|f y|.
  apply: (@ge0_integral_dcoor _ _ _ P i (abse \o f)).
    by apply: measurableT_comp => //.
  by move=> y; exact: abse_ge0.
split=> /integrableP[_ foo]; apply/integrableP; split => //.
- by rewrite -h.
- by apply: (measurableT_comp mf); exact: (@measurable_dcoor n d T i).
- by rewrite h.
Qed.

Lemma integral_dcoor n (d : 'I_n -> measure_display)
    (T : forall i, measurableType (d i)) (P : forall i, probability (T i) R)
    i (f : T i -> \bar R) : (P i).-integrable setT f ->
  \int[\X_(j < n) P j]_x f (x i) = \int[P i]_y f y.
Proof.
move=> intf; have mf := measurable_int _ intf.
transitivity (\int[pushforward (\X_(j < n) P j) (fun x : forall j, T j => x i)]_y
    f y); last first.
