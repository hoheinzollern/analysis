Definition dprod_set (A : forall i, set (T i)) : set (forall i, T i) :=
  [set x | forall i, A i (x i)].

Lemma dprod_setT : dprod_set (fun i => setT) = setT.
Proof. by apply/seteqP; split. Qed.

End dprod_set.
Arguments dprod_set {n d T}.

Lemma dprod_set0 (d : 'I_0 -> measure_display)
    (T : forall i, measurableType (d i)) (A : forall i, set (T i)) :
  dprod_set A = setT.
Proof. by apply/seteqP; split => // x _ i; case: (notF (ltn_ord i)). Qed.

Lemma dsplit_dprod_set n (d : 'I_n.+1 -> measure_display)
    (T : forall i, measurableType (d i)) (A : forall i, set (T i)) :
  dsplit @` dprod_set A = A ord0 `*` dprod_set (fun j => A (lift ord0 j)).
Proof.
rewrite image_dsplit; apply/seteqP; split => [p /= Ap|p /= [Ap0 ApS]].
  split; first by have := Ap ord0; rewrite dcons0.
  by move=> j; have := Ap (lift ord0 j); rewrite dconsS.
move=> i; have [j ->|->] := unliftP ord0 i; first by rewrite dconsS.
by rewrite dcons0.
Qed.

Lemma measurable_dprod_set n (d : 'I_n -> measure_display)
    (T : forall i, measurableType (d i)) (A : forall i, set (T i)) :
  (forall i, measurable (A i)) -> measurable (dprod_set A).
Proof.
elim: n d T A => [d T A mA|n ih d T A mA]; first by rewrite dprod_set0.
have -> : dprod_set A =
    dsplit @^-1` (A ord0 `*` dprod_set (fun j => A (lift ord0 j))).
  apply/seteqP; split=> [x Ax|x [Ax0 AxS] i]; first by split=> //= j; exact: Ax.
  by have [j ->|->] := unliftP ord0 i; [exact: AxS|].
rewrite -[X in measurable X]setTI; apply: measurable_dsplit => //.
by apply: measurableX => //; exact: ih.
Qed.

