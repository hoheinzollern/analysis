(* ## The sigma-algebra generated by a family of dependent projections *)

Definition g_sigma_preimage_dep n (d : 'I_n -> measure_display)
    (rT : forall i, semiRingOfSetsType (d i)) (aT : Type)
    (f : forall i, aT -> rT i) : set_system aT :=
  <<s \big[setU/set0]_(i < n) preimage_set_system setT (f i) measurable >>.

Lemma g_sigma_preimage_dep_comp n (d : 'I_n -> measure_display)
    (T1 : forall i, semiRingOfSetsType (d i))
    {T : choiceType} (f : forall i, T -> T1 i) {T2 : Type} (g : T2 -> T) :
  g_sigma_preimage_dep (fun i => f i \o g) =
  preimage_set_system [set: T2] g (g_sigma_preimage_dep f).
Proof.
rewrite -[RHS]g_sigma_preimageE; congr (<<s _ >>).
rewrite -!bigcup_seq predeqE => B; split.
- move=> [i /= _ [A mA <-{B}]].
  exists (f i @^-1` A); last by rewrite !setTI -comp_preimage.
  by exists i => /=; [rewrite mem_index_enum|exists A => //; rewrite setTI].
- move=> [C [i /= _ [A mA <-{C}]] <-{B}].
  exists i => /=; first by rewrite mem_index_enum.
  by exists A => //; rewrite !setTI -comp_preimage.
Qed.

Definition measure_dprod_display n :
  ('I_n -> measure_display) -> measure_display.
Proof. exact. Qed.

Section measurable_dprod.
Context n (d : 'I_n -> measure_display) (T : forall i, sigmaRingType (d i)).

Let coors : forall i, (forall j, T j) -> T i := fun i x => x i.

Let dprod_set0 : g_sigma_preimage_dep coors set0.
Proof. exact: sigma_algebra0. Qed.

Let dprod_setC A : g_sigma_preimage_dep coors A ->
  g_sigma_preimage_dep coors (~` A).
Proof. exact: sigma_algebraC. Qed.

Let dprod_bigcup (F : _^nat) : (forall i, g_sigma_preimage_dep coors (F i)) ->
  g_sigma_preimage_dep coors (\bigcup_i (F i)).
Proof. exact: sigma_algebra_bigcup. Qed.

HB.instance Definition _ := @isMeasurable.Build (measure_dprod_display d)
  (forall i, T i) (g_sigma_preimage_dep coors)
  dprod_set0 dprod_setC dprod_bigcup.

End measurable_dprod.

Lemma measurable_dcoor n (d : 'I_n -> measure_display)
    (T : forall i, sigmaRingType (d i)) (i : 'I_n) :
  measurable_fun [set: forall j, T j] (fun x => x i).
Proof.
move=> _ Y mY; rewrite setTI; apply: sub_sigma_algebra => /=.
rewrite -bigcup_seq/=; exists i => /=; first by rewrite mem_index_enum.
by exists Y => //; rewrite setTI.
Qed.

Lemma measurable_fun_dcoorP d1 (T1 : measurableType d1) n
    (d : 'I_n -> measure_display) (T : forall i, measurableType (d i))
    (f : T1 -> forall i, T i) :
  measurable_fun [set: T1] f <->
  forall i, measurable_fun [set: T1] (fun x => f x i).
Proof.
apply: (@iff_trans _ (g_sigma_preimage_dep
    (fun i => (fun x => x i) \o f) `<=` measurable)).
  rewrite g_sigma_preimage_dep_comp; split=> [mf A [/= C preC <-]|prefS].
    exact: mf.
  by move=> _ A mA; apply: prefS; exists A.
split=> [coorfS i|mf].
- move=> _ A mA.
  apply: coorfS; apply: sub_sigma_algebra.
  rewrite -bigcup_seq/=; exists i => /=; first by rewrite mem_index_enum.
  by exists A.
- apply: smallest_sub; first exact: sigma_algebra_measurable.
  rewrite -bigcup_seq; apply: bigcup_sub => i _.
  by move=> A [B mB <-]; exact: mf.
Qed.

(* ## Splitting a dependent product into its head and tail *)

Section dprod_split.
Context n (d : 'I_n.+1 -> measure_display)
  (T : forall i, measurableType (d i)).


(* TODO: change name e.g. pair_of_depfun, there's an overload between the d of display and dependent *)
Definition dsplit (x : forall i, T i) :
  T ord0 * (forall j : 'I_n, T (lift ord0 j)) :=
  (x ord0, fun j => x (lift ord0 j)).

Definition dcons (y : T ord0) (z : forall j : 'I_n, T (lift ord0 j)) :
    forall i, T i := fun i =>
  match unliftP ord0 i with
  | UnliftSome j e => ecast k (T k) (esym e) (z j)
  | UnliftNone e => ecast k (T k) (esym e) y
  end.

Lemma dcons0 y z : dcons y z ord0 = y.
Proof.
rewrite /dcons; case: unliftP => [j e|e].
  by exfalso; have := neq_lift ord0 j; rewrite -e eqxx.
by rewrite [esym e]eq_axiomK.
Qed.

Lemma dconsS y z j : dcons y z (lift ord0 j) = z j.
Proof.
rewrite /dcons; case: unliftP => [k e|e]; last first.
  by exfalso; have := neq_lift ord0 j; rewrite e eqxx.
have jk := lift_inj e; move: e; rewrite -{}jk => e.
by rewrite [esym e]eq_axiomK.
Qed.

Lemma dsplitK x : dcons (dsplit x).1 (dsplit x).2 = x.
Proof.
apply/functional_extensionality_dep => i; have [j ->|->] := unliftP ord0 i.
  by rewrite dconsS.
by rewrite dcons0.
Qed.

Lemma dconsK y z : dsplit (dcons y z) = (y, z).
Proof.
rewrite /dsplit dcons0; congr pair.
by apply/functional_extensionality_dep => j; rewrite dconsS.
Qed.

Lemma measurable_dsplit : measurable_fun [set: forall i, T i] dsplit.
Proof.
apply: measurable_fun_pair; first exact: measurable_dcoor.
by apply/measurable_fun_dcoorP => j; exact: measurable_dcoor.
Qed.

Lemma measurable_dcons :
  measurable_fun [set: T ord0 * (forall j : 'I_n, T (lift ord0 j))]
    (fun p => dcons p.1 p.2).
Proof.
apply/measurable_fun_dcoorP => i; have [j ->|->] := unliftP ord0 i.
  have -> : (fun p : T ord0 * (forall j : 'I_n, T (lift ord0 j)) =>
      dcons p.1 p.2 (lift ord0 j)) = (fun p => p.2 j).
    by apply/functional_extensionality_dep => p; rewrite dconsS.
  exact: (measurableT_comp (@measurable_dcoor _ _ _ j) measurable_snd).
have -> : (fun p : T ord0 * (forall j : 'I_n, T (lift ord0 j)) =>
    dcons p.1 p.2 ord0) = fst.
  by apply/functional_extensionality_dep => p; rewrite dcons0.
exact: measurable_fst.
Qed.

Lemma image_dsplit A : dsplit @` A = (fun p => dcons p.1 p.2) @^-1` A.
Proof.
apply/seteqP; split=> [p [x Ax <-]|p Ap]; first by rewrite /= dsplitK.
by exists (dcons p.1 p.2) => //; rewrite dconsK -surjective_pairing.
Qed.

Lemma measurable_image_dsplit A : measurable A -> measurable (dsplit @` A).
Proof.
move=> mA; rewrite image_dsplit.
by rewrite -[X in measurable X]setTI; exact: measurable_dcons.
Qed.

Lemma trivIset_image_dsplit (F : nat -> set (forall i, T i)) :
  trivIset [set: nat] F -> trivIset [set: nat] (fun m => dsplit @` F m).
Proof.
move=> tF; apply/trivIsetP => i j _ _ ij.
move/trivIsetP : tF => /(_ i j Logic.I Logic.I ij).
rewrite -!subset0 => ij0 p [[t Fit <-] [u Fju tu]].
have := ij0 t; apply; split => //.
by rewrite -(dsplitK t) -tu dsplitK.
Qed.

End dprod_split.
Arguments dsplit {n d T}.
Arguments dcons {n d T}.

(* ## The product of a finite family of sigma-finite measures *)

Section dprod_measure_def.
Context {R : realType}.

Definition ord0_fun (T : forall i : 'I_0, Type)
  := (fun i => False_rect _ (notF (ltn_ord i))) : forall i, T i.

Fixpoint dprod_measure n : forall (d : 'I_n -> measure_display)
    (T : forall i, measurableType (d i))
    (P : forall i, {sigma_finite_measure set (T i) -> \bar R}),
    set (forall i, T i) -> \bar R :=
  match n with
  | 0 => fun d T P => \d_(ord0_fun T)
  | m.+1 => fun d T P A =>
      (P ord0 \x^ @dprod_measure m (fun j => d (lift ord0 j))
        (fun j => T (lift ord0 j)) (fun j => P (lift ord0 j)))%E (dsplit @` A)
  end.

End dprod_measure_def.
Arguments dprod_measure {R n d T} P.

Reserved Notation "\X_ ( i < n ) F"
  (at level 36, F at level 36, i, n at level 50,
   format "'[' \X_ ( i  <  n ) '/  '  F ']'").
Reserved Notation "\X_ n F"
  (at level 36, F at level 36, n at level 2,
   format "'[' \X_ n '/  '  F ']'").
Notation "\X_ ( i < n ) F" := (dprod_measure (fun i : 'I_n => F)) : ereal_scope.
(* n-fold product of a single measure; write \X_n.+1 F, not \X_(n.+1) F *)
Notation "\X_ n F" := (dprod_measure (fun _ : 'I_n => F)) : ereal_scope.

Section dprod_measure_measure.
Context {R : realType}.
Local Open Scope ereal_scope.

Let dprod_measureP n (d : 'I_n -> measure_display)
    (T : forall i, measurableType (d i))
    (P : forall i, {sigma_finite_measure set (T i) -> \bar R}) :
  dprod_measure P set0 = 0 /\ (forall A, 0 <= dprod_measure P A) /\
  semi_sigma_additive (dprod_measure P).
Proof.
elim: n d T P => [d T P|n ih d T P] /=.
  by repeat split => //; exact: measure_semi_sigma_additive.
have [ih0 [ih_ge0 ih_sadd]] := ih (fun j => d (lift ord0 j))
  (fun j => T (lift ord0 j)) (fun j => P (lift ord0 j)).
pose build := isMeasure.Build _ _ _
  (@dprod_measure R n _ _ (fun j => P (lift ord0 j))) ih0 ih_ge0 ih_sadd.
pose innerM : measure _ R :=
  HB.pack (@dprod_measure R n _ _ (fun j => P (lift ord0 j))) build.
pose PM : measure _ R := (P ord0 \x^ innerM)%E.
split.
  rewrite image_set0 /product_measure2 /=.
  rewrite (_ : @dprod_measure R n (fun j => d (lift ord0 j))
    (fun j => T (lift ord0 j)) (fun j => P (lift ord0 j)) = innerM)//.
  transitivity (\int[innerM]_x cst 0 x); last by rewrite integral_cst// mul0e.
  by apply: eq_integral => x _ /=; rewrite ysection0 measure0.
split.
  by move=> A; rewrite (_ : @dprod_measure R n (fun j => d (lift ord0 j))
    (fun j => T (lift ord0 j)) (fun j => P (lift ord0 j)) = innerM).
rewrite (_ : @dprod_measure R n (fun j => d (lift ord0 j))
  (fun j => T (lift ord0 j)) (fun j => P (lift ord0 j)) = innerM)//.
rewrite (_ : (P ord0 \x^ innerM)%E = PM)//.
move=> F mF dF mUF.
rewrite image_bigcup; apply: measure_semi_sigma_additive.
- by move=> i; exact: measurable_image_dsplit.
- exact: trivIset_image_dsplit.
- by apply: bigcup_measurable => j _; exact: measurable_image_dsplit.
Qed.

HB.instance Definition _ n (d : 'I_n -> measure_display)
    (T : forall i, measurableType (d i))
    (P : forall i, {sigma_finite_measure set (T i) -> \bar R}) :=
  isMeasure.Build _ _ _ (dprod_measure P)
    (dprod_measureP P).1 (dprod_measureP P).2.1 (dprod_measureP P).2.2.

End dprod_measure_measure.

